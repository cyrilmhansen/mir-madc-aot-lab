#!/usr/bin/env python3
"""Freeze Cycle44 scalar signatures and generate exact-prototype native call stubs."""
import json
from pathlib import Path

ROOT=Path(__file__).resolve().parents[2]
BUILD=ROOT/'experiments/mir-api-coverage/build'
RESULTS=ROOT/'results/cycle44-mir-abi-calls'
BUILD.mkdir(parents=True,exist_ok=True); RESULTS.mkdir(parents=True,exist_ok=True)
shapes=[]
for n in [0,1,2,4,5,6,7,8,9,10]: shapes.append(('i64_only',["I64"]*n))
for n in [1,2,4,5,6,7,8,9,10]: shapes.append(('double_only',["D"]*n))
for n in range(2,11): shapes.append(('alternating_int_double',["I64" if i%2==0 else "D" for i in range(n)]))
for n in range(3,11):
    split=(n+1)//2
    shapes.append(('integer_then_double',["I64"]*split+["D"]*(n-split)))
for n in range(3,11):
    split=(n+1)//2
    shapes.append(('double_then_integer',["D"]*split+["I64"]*(n-split)))
shapes += [
 ('mixed_width',["I32","U64","I64","D"]),
 ('mixed_reversed',["D","I32","D","I64"]),
 ('mixed_register_pressure',["I32","D","U64","D","I64"]),
 ('float_double_integer',["F","I64","D","U64","F"]),
]
confirmatory_count=len(shapes)
shapes += [
 ('exploratory_mixed_gp_spill',["I64"]*8+["D"]*2),
 ('exploratory_mixed_sse_spill',["I64"]*2+["D"]*8),
 ('exploratory_mixed_gp_boundary',["I64"]*7+["D"]*3),
 ('exploratory_mixed_sse_boundary',["I64"]*3+["D"]*7),
]
assert confirmatory_count==48 and len(shapes)==52, len(shapes)
GP={'I64','U64','I32','U32','P'}; FP={'F','D'}
regs_gp=['RDI','RSI','RDX','RCX','R8','R9']; regs_fp=[f'XMM{i}' for i in range(8)]
specs=[]
for i,(family,types) in enumerate(shapes):
    gp=fp=stack=0; locations=[]
    for j,t in enumerate(types):
        if t in GP:
            if gp<len(regs_gp): loc=regs_gp[gp]; gp+=1
            else: loc=f'STACK+{stack*8}'; stack+=1
        else:
            if fp<len(regs_fp): loc=regs_fp[fp]; fp+=1
            else: loc=f'STACK+{stack*8}'; stack+=1
        locations.append({'index':j,'type':t,'class':'GP' if t in GP else 'SSE','location':loc})
    ret='D' if any(t in FP for t in types) else 'I64'
    specs.append({'id':i,'name':f'abi_case_{i:02d}','family':family,'return':ret,'arguments':types,'register_counts':{'GP':min(gp,6),'SSE':min(fp,8)},'stack_argument_count':stack,'argument_locations':locations,'return_location':'XMM0' if ret=='D' else 'RAX','tier':'confirmatory' if i<confirmatory_count else 'exploratory'})
(RESULTS/'generated-signatures.json').write_text(json.dumps({'target':'x86_64 System V AMD64','confirmatory_count':confirmatory_count,'exploratory_count':len(specs)-confirmatory_count,'case_count':len(specs),'signature_shapes':specs},indent=2)+'\n')

mirtype={'I64':'MIR_T_I64','U64':'MIR_T_U64','I32':'MIR_T_I32','U32':'MIR_T_U32','P':'MIR_T_P','F':'MIR_T_F','D':'MIR_T_D'}
ctype={'I64':'int64_t','U64':'uint64_t','I32':'int32_t','U32':'uint32_t','P':'void *','F':'float','D':'double'}
mac={'I64':'V_I64','U64':'V_U64','I32':'V_I32','U32':'V_U32','P':'V_P','F':'V_F','D':'V_D'}

def literal(t,i):
    if t=='I64': return f'((int64_t)(seed*3+{i+1}))'
    if t=='U64': return f'((uint64_t)(seed*2+{i+3}))'
    if t=='I32': return f'((int32_t)(seed*3+{i}-2))'
    if t=='U32': return f'((uint32_t)(seed*3+{i+2}))'
    if t=='F': return f'((float)(seed+{i+1})*0.25f)'
    if t=='D': return f'((double)(seed+{i+1})*0.5)'
    if t=='P': return 'NULL'
    raise KeyError(t)

lines=['/* Generated by cycle44-abi-matrix.py; exact C prototypes per signature. */','typedef enum { ABI_I64, ABI_U64, ABI_I32, ABI_U32, ABI_P, ABI_F, ABI_D } AbiType;', 'typedef struct { const char *name; int n; AbiType args[10]; int returns_double; } AbiCase;']
for s in specs:
    vals=', '.join('ABI_'+t for t in s['arguments'])
    lines.append(f'{{0}}') if False else None
lines.append(f'#define ABI_CASE_COUNT {len(specs)}')
lines.append(f'#define ABI_CONFIRMATORY_COUNT {confirmatory_count}')
lines.append(f'static const AbiCase abi_cases[{len(specs)}] = {{')
for s in specs:
    vals=', '.join('ABI_'+t for t in s['arguments']) or 'ABI_I64'
    lines.append(f'  {{"{s["name"]}",{len(s["arguments"])},{{{vals}}},{1 if s["return"]=="D" else 0}}},')
lines.append('};')
for s in specs:
    i=s['id']; ts=s['arguments']; ret=s['return']; fnret='double' if ret=='D' else 'int64_t'
    args=', '.join(f'{ctype[t]} a{j}' for j,t in enumerate(ts)) or 'void'
    callargs=', '.join(literal(t,j) for j,t in enumerate(ts))
    lines.append(f'static {fnret} abi_call_{i:02d}(void *target, int seed) {{ (void)seed; typedef {fnret} (*Fn)({args}); Fn f=(Fn)target; return f({callargs}); }}')
    if ret=='D':
        terms=[f'((double)({literal(t,j)}))*{3+2*j}.0' for j,t in enumerate(ts)]
        expr=' + '.join(terms) if terms else '0.0'
        lines.append(f'static double abi_oracle_{i:02d}(int seed) {{ return {expr}; }}')
    else:
        terms=[f'((int64_t)({literal(t,j)}))*INT64_C({3+2*j})' for j,t in enumerate(ts)]
        expr=' + '.join(terms) if terms else 'INT64_C(0)'
        lines.append(f'static int64_t abi_oracle_{i:02d}(int seed) {{ (void)seed; return {expr}; }}')
    argsfill=', '.join(f'{mac[t]}({literal(t,j)})' for j,t in enumerate(ts))
    lines.append(f'static void abi_fill_{i:02d}(int seed, MIR_val_t *v) {{')
    if not ts: lines.append('  (void)seed; (void)v;')
    for j,t in enumerate(ts):
        field={'I64':'i','U64':'u','I32':'i','U32':'u','P':'a','F':'f','D':'d'}[t]
        lines.append(f'  v[{j}].{field}={literal(t,j)};')
    lines.append('}')
    lines.append(f'static void abi_run_{i:02d}(void *target,int seed,int64_t *iv,double *dv) {{')
    lines.append(f'  if (abi_cases[{i}].returns_double) *dv=abi_call_{i:02d}(target,seed); else *iv=abi_call_{i:02d}(target,seed);')
    lines.append('}')
lines.append('static void abi_fill_dispatch(int id,int seed,MIR_val_t *v) { switch(id) {')
for s in specs: lines.append(f'  case {s["id"]}: abi_fill_{s["id"]:02d}(seed,v); break;')
lines.append('  default: abort(); } }')
lines.append('static int64_t abi_oracle_int_dispatch(int id,int seed) { switch(id) {')
for s in specs:
    if s['return']!='D': lines.append(f'  case {s["id"]}: return abi_oracle_{s["id"]:02d}(seed);')
lines.append('  default: abort(); } }')
lines.append('static double abi_oracle_double_dispatch(int id,int seed) { switch(id) {')
for s in specs:
    if s['return']=='D': lines.append(f'  case {s["id"]}: return abi_oracle_{s["id"]:02d}(seed);')
lines.append('  default: abort(); } }')
lines.append('static void abi_run_dispatch(int id,void *target,int seed,int64_t *iv,double *dv) { switch(id) {')
for s in specs: lines.append(f'  case {s["id"]}: abi_run_{s["id"]:02d}(target,seed,iv,dv); break;')
lines.append('  default: abort(); } }')
( BUILD/'cycle44-signature-stubs.inc').write_text('\n'.join(lines)+'\n')

# Exact native C caller for ET_REL and dlopen shared-library artifacts.
client=['#define _GNU_SOURCE','#include <dlfcn.h>','#include <inttypes.h>','#include <stdint.h>','#include <stdio.h>','#include <stdlib.h>','#include <string.h>','']
for s in specs:
    args=', '.join(f'{ctype[t]} a{j}' for j,t in enumerate(s['arguments'])) or 'void'
    rtype='double' if s['return']=='D' else 'int64_t'
    client.append(f'extern {rtype} {s["name"]}({args});')
client += ['extern int64_t abi_internal_caller(int64_t,int64_t,int64_t,int64_t,int64_t,int64_t,int64_t,int64_t);','extern int64_t abi_import_integer8(int64_t,int64_t,int64_t,int64_t,int64_t,int64_t,int64_t,int64_t);','extern int64_t abi_import_pointer(uint8_t*,int64_t);','extern double abi_import_mixed(int64_t,double,int64_t,double,int64_t,double,int64_t,double);','extern double abi_c_mixed(int64_t,double,int64_t,double,int64_t,double,int64_t,double);','extern int64_t abi_c_integer8(int64_t,int64_t,int64_t,int64_t,int64_t,int64_t,int64_t,int64_t);','']
client += ['int64_t abi_c_integer8(int64_t a0,int64_t a1,int64_t a2,int64_t a3,int64_t a4,int64_t a5,int64_t a6,int64_t a7) { return 3*a0+5*a1+7*a2+11*a3+13*a4+17*a5+19*a6+23*a7; }','double abi_c_mixed(int64_t a0,double a1,int64_t a2,double a3,int64_t a4,double a5,int64_t a6,double a7) { return 3.0*a0+5.0*a1+7.0*a2+11.0*a3+13.0*a4+17.0*a5+19.0*a6+23.0*a7; }','int64_t abi_c_pointer(uint8_t *p,int64_t n) { int64_t s=0; for(int64_t i=0;i<n;i++){p[i]=(uint8_t)(i*7+3);s+=(int64_t)p[i]*(i+1);} return s; }','']
client.append('static int run_linked(void) { int failures=0;')
for s in specs:
    i=s['id']; ts=s['arguments']; ret=s['return']; rtype='double' if ret=='D' else 'int64_t'
    call=', '.join(literal(t,j) for j,t in enumerate(ts))
    exp_terms=[f'((double)({literal(t,j)}))*{3+2*j}.0' for j,t in enumerate(ts)] if ret=='D' else [f'((int64_t)({literal(t,j)}))*INT64_C({3+2*j})' for j,t in enumerate(ts)]
    exp=' + '.join(exp_terms) if exp_terms else ('0.0' if ret=='D' else 'INT64_C(0)')
    client.append(f'  for(int seed=0;seed<3;seed++) {{ {rtype} got={s["name"]}({call}); {rtype} want={exp}; if(got!=want) {{ fprintf(stderr,"{s["name"]} seed=%d got mismatch\\n",seed); failures++; }} }}')
client += ['  int64_t want=abi_c_integer8(1,2,3,4,5,6,7,8);','  if(abi_import_integer8(1,2,3,4,5,6,7,8)!=want) failures++;','  double mw=abi_c_mixed(1,.5,2,1.0,3,1.5,4,2.0);','  if(abi_import_mixed(1,.5,2,1.0,3,1.5,4,2.0)!=mw) failures++;','  int64_t internal=1*29+8*31+abi_c_integer8(1,2,3,4,5,6,7,8)+2*8+4*7+6*6+8*5+10*4+12*3+14*2+16*1;','  if(abi_internal_caller(1,2,3,4,5,6,7,8)!=internal) failures++;','  uint8_t bytes[18]; memset(bytes,0xa5,sizeof bytes); int64_t ps=0; for(int i=0;i<8;i++){bytes[5+i]=(uint8_t)(i*7+3);ps+=(int64_t)bytes[5+i]*(i+1);} if(abi_import_pointer(bytes+5,8)!=ps) failures++; for(int i=0;i<5;i++)if(bytes[i]!=0xa5||bytes[13+i]!=0xa5)failures++;',f'  printf("linked ABI cases={len(specs)} (confirmatory={confirmatory_count}) failures=%d\\n",failures); return failures?1:0;','}']
client.append('static int run_shared(const char *path) {')
client += ['  void *h=dlopen(path,RTLD_NOW|RTLD_LOCAL); if(!h){fprintf(stderr,"dlopen: %s\\n",dlerror()); return 2;} int failures=0;']
for s in specs:
    i=s['id']; ts=s['arguments']; ret=s['return']; rtype='double' if ret=='D' else 'int64_t'
    args=', '.join(f'{ctype[t]} a{j}' for j,t in enumerate(ts)) or 'void'
    call=', '.join(literal(t,j) for j,t in enumerate(ts))
    exp_terms=[f'((double)({literal(t,j)}))*{3+2*j}.0' for j,t in enumerate(ts)] if ret=='D' else [f'((int64_t)({literal(t,j)}))*INT64_C({3+2*j})' for j,t in enumerate(ts)]
    exp=' + '.join(exp_terms) if exp_terms else ('0.0' if ret=='D' else 'INT64_C(0)')
    client.append(f'  {{ typedef {rtype}(*Fn)({args}); Fn f=(Fn)dlsym(h,"{s["name"]}"); if(!f){{failures++;}} else for(int seed=0;seed<3;seed++){{{rtype} got=f({call}); {rtype} want={exp}; if(got!=want) failures++;}} }}')
client += ['  { typedef int64_t(*Fn)(int64_t,int64_t,int64_t,int64_t,int64_t,int64_t,int64_t,int64_t); Fn f=(Fn)dlsym(h,"abi_internal_caller"); if(!f||f(1,2,3,4,5,6,7,8)!=(1*29+8*31+abi_c_integer8(1,2,3,4,5,6,7,8)+2*8+4*7+6*6+8*5+10*4+12*3+14*2+16*1)) failures++; }','  { typedef int64_t(*Fn)(int64_t,int64_t,int64_t,int64_t,int64_t,int64_t,int64_t,int64_t); Fn f=(Fn)dlsym(h,"abi_import_integer8"); if(!f||f(1,2,3,4,5,6,7,8)!=abi_c_integer8(1,2,3,4,5,6,7,8)) failures++; }','  { typedef double(*Fn)(int64_t,double,int64_t,double,int64_t,double,int64_t,double); Fn f=(Fn)dlsym(h,"abi_import_mixed"); if(!f||f(1,.5,2,1.0,3,1.5,4,2.0)!=abi_c_mixed(1,.5,2,1.0,3,1.5,4,2.0)) failures++; }','  { typedef int64_t(*Fn)(uint8_t*,int64_t); Fn f=(Fn)dlsym(h,"abi_import_pointer"); uint8_t b[18];memset(b,0xa5,sizeof b);int64_t sum=0;for(int i=0;i<8;i++){b[5+i]=(uint8_t)(i*7+3);sum+=(int64_t)b[5+i]*(i+1);}memset(b,0xa5,sizeof b);if(!f||f(b+5,8)!=sum)failures++;for(int i=0;i<5;i++)if(b[i]!=0xa5||b[13+i]!=0xa5)failures++; }']
client += ['  if(dlclose(h)!=0) failures++;',f'  printf("shared ABI cases={len(specs)} (confirmatory={confirmatory_count}) failures=%d\\n",failures); return failures?1:0;','}','int main(int argc,char **argv) { if(argc==2) return run_shared(argv[1]); return run_linked(); }']
(BUILD/'cycle44-native-client.c').write_text('\n'.join(client)+'\n')
print(json.dumps({'signatures':len(specs),'generated_header':str(BUILD/'cycle44-signature-stubs.inc'),'generated_client':str(BUILD/'cycle44-native-client.c')}))
